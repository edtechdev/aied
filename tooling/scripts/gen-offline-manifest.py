#!/usr/bin/env python3
"""Generate src/data/offlineArtifacts.ts from the tracked release catalog.

The catalog (`tooling/offline-editions.json`) is the single source of truth for
which files exist and what their stable release URLs are. It deliberately does
not depend on binaries being present in a clean checkout: the site can be built
from the catalog alone.

Run this after publishing or approving a catalog change. It is a generated view,
like conceptIndex.ts; edit the catalog, never this file.
"""
import json
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / 'tooling' / 'scripts'))
import offline_release  # noqa: E402

OUT = REPO / 'src' / 'data' / 'offlineArtifacts.ts'
SITE = offline_release.load_site()


def main():
    catalog = offline_release.load_catalog(site=SITE)
    manifest = offline_release.manifest_from_catalog(catalog, SITE)
    default = offline_release.default_locale(SITE)

    out_path = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else OUT
    lines = [
        '// GENERATED by tooling/scripts/gen-offline-manifest.py - do not edit by hand.',
        '// Lists the release-backed offline artifacts, per locale, so the site can',
        '// link a locale\'s own file and fall back to the default locale when it has none.',
        '',
        'export type OfflineArtifact = { url: string; bytes: number };',
        '',
        'export const offlineArtifacts: Record<string, Record<string, OfflineArtifact>> = '
        + json.dumps(manifest, indent=2, ensure_ascii=False)
        + ';',
        '',
        'export const defaultLocale = ' + json.dumps(default) + ';',
        '',
    ]
    out_path.write_text('\n'.join(lines), encoding='utf-8')

    try:
        shown = out_path.relative_to(REPO)
    except ValueError:
        shown = out_path
    print(f'wrote {shown}')
    for code, arts in manifest.items():
        detail = ', '.join(f'{k}={v["bytes"]}' for k, v in arts.items())
        print(f'  {code}: {detail}')
    return 0


if __name__ == '__main__':
    sys.exit(main())

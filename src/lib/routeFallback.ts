/**
 * English fallback for locale-prefixed URLs of pages that have no translation.
 *
 * The site is a static build on GitHub Pages: a locale path either exists as a
 * file or the host serves `404.html`, and there is no server to issue a 301.
 * Most translations cover only part of the corpus (Greek has ~130 of ~2,650
 * pages), so a shared link such as `/aied/el/concepts/ai-feedback-quality/`
 * lands on the not-found page even though the page exists in English.
 *
 * The fix is one document, not 77,000 redirect stubs: `404.html` carries the
 * hashes of every default-locale route, strips the locale prefix from the URL it
 * was served for, and sends the reader to the English page when that page exists.
 * A path with no English counterpart keeps the localized not-found copy it
 * already renders.
 *
 * Why hashes instead of the route strings: the article collection alone is
 * ~2,300 long slugs (~140 KB of JSON), and the error document is fetched for
 * every unknown path, including bots. A 32-bit hash is 6 base-36 characters, so
 * the whole corpus costs ~20 KB. A hash collision can only send a reader to a
 * path that does not exist in English, which ends on the English 404 page — the
 * same place they would have landed — so collisions are harmless, not silent
 * corruption.
 */

/** FNV-1a (32-bit). Must stay byte-identical to the copy in the inline script. */
export function fnv1a(value: string): number {
  let hash = 0x811c9dc5;
  for (let i = 0; i < value.length; i += 1) {
    hash ^= value.charCodeAt(i);
    hash = Math.imul(hash, 0x01000193) >>> 0;
  }
  return hash >>> 0;
}

/**
 * The inline script the 404 document runs in <head>, before anything paints.
 *
 * It reads only `location` and the embedded hash list: no fetch, no dependency
 * on the service worker, and no build-time link rewriting in the locales. The
 * query string and fragment are carried over, so `?embed` (the chromeless view
 * other sites iframe) survives the hop.
 */
export function fallbackRedirectScript(options: {
  hashes: string[]; // base-36, ascending
  basePath: string;
  locales: string[];
}): string {
  const { hashes, basePath, locales } = options;
  return `
    // Untranslated pages: send a locale URL to its English counterpart.
    // Generated by src/lib/routeFallback.ts — the hash list and this function
    // must stay in sync, and both are built from the same collection at build
    // time, so a new page is covered without editing this string.
    (function () {
      var BASE = ${JSON.stringify(basePath)};
      var CODES = ${JSON.stringify(locales)};
      var HASHES = "${hashes.join(',')}".split(',');
      var sorted = [];
      for (var i = 0; i < HASHES.length; i++) sorted.push(parseInt(HASHES[i], 36));
      sorted.sort(function (a, b) { return a - b; });

      function fnv1a(value) {
        var hash = 0x811c9dc5;
        for (var j = 0; j < value.length; j++) {
          hash ^= value.charCodeAt(j);
          hash = Math.imul(hash, 0x01000193) >>> 0;
        }
        return hash >>> 0;
      }
      function known(route) {
        var h = fnv1a(route);
        var lo = 0, hi = sorted.length - 1;
        while (lo <= hi) {
          var mid = (lo + hi) >> 1;
          if (sorted[mid] === h) return true;
          if (sorted[mid] < h) lo = mid + 1; else hi = mid - 1;
        }
        return false;
      }

      var path = location.pathname;
      if (path.indexOf(BASE + '/') !== 0) return;
      var segs = path.slice(BASE.length).split('/').filter(Boolean);
      // No locale segment (a plain English miss), or the locale's own home page:
      // nothing to redirect.
      if (segs.length < 2 || CODES.indexOf(segs[0]) === -1) return;
      var route = '/' + segs.slice(1).join('/');
      // Unknown in English too: keep the localized not-found copy.
      if (!known(route)) return;
      location.replace(BASE + route + '/' + location.search + location.hash);
    })();
  `;
}
